#!/bin/sh
# gen_examples.sh -- regenerate doc/_examples.txt, the source of the "Examples"
# page of the Doxygen API documentation.
#
# Run from doc/ (sh gen_examples.sh) after adding, removing or retitling any
# demos/*.cpp, then re-run doxygen. The Examples page introduces both kinds of
# shipped demos and carries one titled Doxygen page per compiled C++ exemplar
# (title = the \brief line of the .cpp, body = the file itself via \include,
# so the source is cross-referenced to the classes it uses); the .cpp files
# keep their own \example declarations so that class pages retain their
# "Examples:" back-references. The fst4 config demos (demos/*.cfg) are
# command-line material and are not reproduced here: the page points to the
# Demos page of the FST4 web site, which browses them with their descriptions
# (through the \sitepage alias, a link in the web build of the reference and
# plain text in a standalone build -- see ALIASES in doxygen.cfg).
set -e
cd "$(dirname "$0")"
out=_examples.txt

cpp_title() { grep -m1 '\\brief' "$1" | sed 's/.*\\brief *//; s/ *$//'; }
page_id()   { basename "$1" | sed 's/\./_/g'; }
ncfg=$(ls ../demos/demo*.cfg | wc -l | tr -d ' '); ncpp=$(ls ../demos/demo*.cpp | wc -l | tr -d ' ')

{
cat <<'HEAD' | sed "s/@NCFG@/$ncfg/; s/@NCPP@/$ncpp/"
/* GENERATED by gen_examples.sh from the headers of the demo files -- do not
   edit by hand, re-run the script instead (see its header for the rules). */

/*! \page examples_all Examples

FST4 ships two kinds of examples.

The <b>fst4 command-line configs</b> -- the @NCFG@ `.cfg` files in `demos/` --
are ready-to-run scenarios: from the distribution root, `fst4 --config
demos/demoNN.cfg` reproduces the demo, and the header comment of each file
states its title, protocol and expected runtime. They are browsed with their
descriptions \sitepage{demos.html,on the Demos page of the FST4 web site};
the flags are documented in the \clidoc{fst4 CLI reference}.

The <b>compiled C++ exemplars</b> -- the @NCPP@ `.cpp` files in `demos/`, listed
below -- show the same kind of scenario programmed directly against the
library API; each is a CMake target of its own name, run from the
distribution root (data paths are relative), and reproduces the result of
its config-file twin. Their sources are shown in full, every class linked to
its reference page.

The demos are numbered by topic: demo1x basic sub-optimal feature selection,
demo2x more sub-optimal methods, demo3x high-dimensional tasks and DAF
ranking, demo4x optimal search, demo5x anti-overfitting techniques, demo6x
complementary scenarios. A trailing "t" marks a threaded variant.

HEAD
for f in ../demos/demo*.cpp; do printf '%s\n' "- \\subpage $(page_id "$f")"; done
printf '*/\n'
for f in ../demos/demo*.cpp; do
  n=$(basename "$f"); s=${n%.cpp}
  printf '\n/*! \\page %s %s — %s\n' "$(page_id "$f")" "$n" "$(cpp_title "$f")"
  printf '    The compiled C++ exemplar of this scenario, programmed against the library\n'
  printf '    API (CMake target `%s`); the config-file form of the same demo is\n' "$s"
  printf '    `demos/%s.cfg`, described \\sitepage{demos.html#%s,on the Demos page of the FST4 web site}.\n' "$s" "$s"
  printf '    \\include %s */\n' "$n"
done
} > "$out"
echo "$out: $(grep -c '\\page' "$out") pages"
